const { z } = require('zod');
const { parseId } = require('../utils/http');
const { parseAmountToPence } = require('../utils/money');

// Request-body and query schemas. Every object schema is strict: a field
// the API doesn't expect (user_id, balance, is_anomaly, ...) is a 400, so a
// client can never set server-owned columns by adding them to a request.

const id = z.unknown().transform((value, ctx) => {
  if (value === undefined) {
    ctx.addIssue({ code: 'custom', message: 'is required' });
    return z.NEVER;
  }
  const parsed = parseId(value);
  if (parsed === null) {
    ctx.addIssue({ code: 'custom', message: 'must be a positive whole number' });
    return z.NEVER;
  }
  return parsed;
});

// Absent, null or '' all mean "no category".
const optionalId = z.unknown().transform((value, ctx) => {
  if (value === undefined || value === null || value === '') return null;
  const parsed = parseId(value);
  if (parsed === null) {
    ctx.addIssue({ code: 'custom', message: 'must be a positive whole number' });
    return z.NEVER;
  }
  return parsed;
});

// Pounds in (number or decimal string), integer pence out.
const amount = z.unknown().transform((value, ctx) => {
  if (value === undefined) {
    ctx.addIssue({ code: 'custom', message: 'is required' });
    return z.NEVER;
  }
  const result = parseAmountToPence(value);
  if (!result.ok) {
    ctx.addIssue({ code: 'custom', message: result.error.replace(/^amount /, '') });
    return z.NEVER;
  }
  return result.pence;
});

// A real calendar date (2026-02-30 is refused) within a sensible range.
const isoDate = z.iso.date({ message: 'must be a date in YYYY-MM-DD format' })
  .refine((d) => d >= '1970-01-01' && d <= '2100-12-31', { message: 'must be between 1970 and 2100' });

const description = z.string().trim().max(255, { message: 'must be 255 characters or fewer' })
  .nullish()
  .transform((v) => (v ? v : null));

const email = z.string().trim().toLowerCase()
  .max(255, { message: 'must be 255 characters or fewer' })
  .pipe(z.email({ message: "doesn't look like a valid email address" }));

const newPassword = z.string()
  .min(8, { message: 'must be between 8 and 72 characters' })
  .max(72, { message: 'must be between 8 and 72 characters' });

const anyPassword = z.string().min(1, { message: 'is required' }).max(1024, { message: 'is too long' });

// 64 hex characters: 32 random bytes, as generated by utils/tokens.js.
const emailToken = z.string().regex(/^[0-9a-f]{64}$/, { message: 'is invalid' });

const schemas = {
  register: z.strictObject({
    email,
    password: newPassword,
    honeypot: z.string().max(500).optional(),
    formRenderedAt: z.number().nullish(),
  }),

  login: z.strictObject({ email, password: anyPassword }),

  emailOnly: z.strictObject({ email }),

  verifyEmail: z.strictObject({ token: emailToken }),

  resetPassword: z.strictObject({ token: emailToken, password: newPassword }),

  deleteAccount: z.strictObject({ password: anyPassword }),

  createAccount: z.strictObject({
    name: z.string().trim().min(1, { message: 'is required' }).max(100, { message: 'must be 100 characters or fewer' }),
    type: z.enum(['current', 'savings', 'credit'], { message: 'must be current, savings or credit' }),
  }),

  createCategory: z.strictObject({
    name: z.string().trim().min(1, { message: 'is required' }).max(40, { message: 'must be 40 characters or fewer' }),
  }),

  createTransaction: z.strictObject({
    account_id: id,
    category_id: optionalId.optional(),
    amount,
    description: description.optional(),
    date: isoDate,
  }),

  updateTransaction: z.strictObject({
    account_id: id.optional(),
    category_id: optionalId.optional(),
    amount: amount.optional(),
    description: description.optional(),
    date: isoDate.optional(),
  }).refine((body) => Object.keys(body).length > 0, { message: 'Nothing to update' }),

  createRecurring: z.strictObject({
    account_id: id,
    category_id: optionalId.optional(),
    amount,
    description: description.optional(),
    frequency: z.enum(['weekly', 'monthly'], { message: 'must be "weekly" or "monthly"' }),
    start_date: isoDate,
  }),

  // The schedule (frequency, next run, start day) can't be edited: that
  // would let a client skip or repeat payments. Delete and recreate instead.
  updateRecurring: z.strictObject({
    amount: amount.optional(),
    description: description.optional(),
    category_id: optionalId.optional(),
  }).refine((body) => Object.keys(body).length > 0, { message: 'Nothing to update' }),

  // Query strings arrive as text, so numbers are coerced.
  listTransactionsQuery: z.strictObject({
    page: z.coerce.number().int().min(1, { message: 'must be 1 or more' }).max(100000).default(1),
    limit: z.coerce.number().int().min(1).max(100, { message: 'must be between 1 and 100' }).default(25),
    account_id: id.optional(),
    category_id: id.optional(),
    from: isoDate.optional(),
    to: isoDate.optional(),
  }).refine((q) => !q.from || !q.to || q.from <= q.to, { message: 'from must be on or before to', path: ['from'] }),
};

// Validates input against a schema. Returns { ok: true, data } or
// { ok: false, error } with one short, human-readable message that never
// includes a stack trace or internal detail.
function validate(schema, input) {
  const result = schema.safeParse(input ?? {});
  if (result.success) return { ok: true, data: result.data };

  const issue = result.error.issues[0];
  if (issue.code === 'unrecognized_keys') {
    return { ok: false, error: `Unexpected field${issue.keys.length > 1 ? 's' : ''}: ${issue.keys.join(', ')}` };
  }
  const field = issue.path.join('.');
  if (issue.code === 'invalid_type' && issue.input === undefined) {
    return { ok: false, error: `${field} is required` };
  }
  return { ok: false, error: field ? `${field} ${issue.message}` : issue.message };
}

schemas.updateCategory = schemas.createCategory;

module.exports = { schemas, validate };
